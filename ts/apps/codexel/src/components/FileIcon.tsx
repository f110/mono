// FileIcon shows the icon of the file type determined by the name of the file. The generic icon is shown for the
// unknown file types.
export const FileIcon = ({ path }: { path: string }) => <SvgIcon src={fileIconOf(path)} />

// FolderIcon shows the icon of the directory. open shows the opened folder.
export const FolderIcon = ({ open }: { open: boolean }) => <SvgIcon src={open ? folderOpenIcon : folderIcon} />

const SvgIcon = ({ src }: { src: string }) => <Box component="img" src={src} alt="" sx={{ width: 16, height: 16, flexShrink: 0 }} />

// fileIconOf returns the icon of the file. The file name is matched first, then the extensions from the longest one.
const fileIconOf = (path: string) => {
  const name = (path.split('/').pop() ?? path).toLowerCase()
  const byName = iconsByName[name]
  if (byName) {
    return byName
  }
  for (let i = name.indexOf('.'); i >= 0; i = name.indexOf('.', i + 1)) {
    const icon = iconsByExtension[name.slice(i + 1)]
    if (icon) {
      return icon
    }
  }
  return fileIcon
}
