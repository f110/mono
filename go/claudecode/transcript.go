// Package claudecode reads the transcripts of the sessions of Claude Code.
//
// The transcript is the internal format of Claude Code and it is not published as a specification. All code depending
// on the format is in this package.
package claudecode

import (
	"bytes"
	"encoding/json"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"
	"unicode/utf8"

	"go.f110.dev/xerrors"
)

type EntryKind int

const (
	EntryKindUserPrompt EntryKind = iota + 1
	EntryKindAssistantText
	EntryKindToolUse
	EntryKindToolResult
)

// maxTextLength is the max length in bytes of the text of the tool call and the result. The result of the tool may be
// the whole content of the file.
const maxTextLength = 4000

// Entry is an entry of the timeline of the session.
type Entry struct {
	Kind EntryKind
	Time time.Time
	// Text is the prompt, the text of the agent, the summary of the input of the tool or the result of the tool.
	Text      string
	ToolName  string
	ToolUseID string
	IsError   bool
}

var sessionIDPattern = regexp.MustCompile(`^[0-9A-Za-z-]+$`)

// DefaultProjectsDir returns ~/.claude/projects.
func DefaultProjectsDir() (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", xerrors.WithStack(err)
	}
	return filepath.Join(home, ".claude", "projects"), nil
}

// FindTranscript returns the path of the transcript of the session in projectsDir. It returns an empty string if the
// transcript doesn't exist yet. The directory of the transcript is derived from the working directory where the session
// started, so the transcript is searched by the session ID.
func FindTranscript(projectsDir, sessionID string) (string, error) {
	if !sessionIDPattern.MatchString(sessionID) {
		return "", xerrors.Definef("invalid session ID: %q", sessionID).WithStack()
	}
	matches, err := filepath.Glob(filepath.Join(projectsDir, "*", sessionID+".jsonl"))
	if err != nil {
		return "", xerrors.WithStack(err)
	}
	if len(matches) == 0 {
		return "", nil
	}
	return matches[0], nil
}

// Transcript follows the transcript file which Claude Code appends during the session.
type Transcript struct {
	path   string
	offset int64

	aiTitle     string
	firstPrompt string
	lastPrompt  string
}

func NewTranscript(path string) *Transcript {
	return &Transcript{path: path}
}

// Title returns the title of the session generated by Claude Code. If there is no title, it returns the first line of
// the first prompt of the user.
func (t *Transcript) Title() string {
	if t.aiTitle != "" {
		return t.aiTitle
	}
	first, _, _ := strings.Cut(t.firstPrompt, "\n")
	return first
}

// LastPrompt returns the latest prompt of the user.
func (t *Transcript) LastPrompt() string {
	return t.lastPrompt
}

// Update reads the lines appended since the last call and returns the entries of them. The incomplete line at the end
// is read by the next call.
func (t *Transcript) Update() ([]*Entry, error) {
	f, err := os.Open(t.path)
	if err != nil {
		return nil, xerrors.WithStack(err)
	}
	defer f.Close()
	if _, err := f.Seek(t.offset, io.SeekStart); err != nil {
		return nil, xerrors.WithStack(err)
	}
	buf, err := io.ReadAll(f)
	if err != nil {
		return nil, xerrors.WithStack(err)
	}
	end := bytes.LastIndexByte(buf, '\n')
	if end < 0 {
		return nil, nil
	}
	t.offset += int64(end + 1)

	var entries []*Entry
	for line := range bytes.Lines(buf[:end+1]) {
		entries = append(entries, t.parseLine(line)...)
	}
	return entries, nil
}

type record struct {
	Type        string    `json:"type"`
	Timestamp   time.Time `json:"timestamp"`
	IsSidechain bool      `json:"isSidechain"`
	IsMeta      bool      `json:"isMeta"`
	Origin      *struct {
		Kind string `json:"kind"`
	} `json:"origin"`
	Message *struct {
		Content json.RawMessage `json:"content"`
	} `json:"message"`
	AITitle    string `json:"aiTitle"`
	LastPrompt string `json:"lastPrompt"`
}

type contentBlock struct {
	Type      string          `json:"type"`
	Text      string          `json:"text"`
	Name      string          `json:"name"`
	ID        string          `json:"id"`
	Input     json.RawMessage `json:"input"`
	ToolUseID string          `json:"tool_use_id"`
	Content   json.RawMessage `json:"content"`
	IsError   bool            `json:"is_error"`
}

// parseLine returns the entries of the line. The lines which can't be parsed are ignored because the format may
// change.
func (t *Transcript) parseLine(line []byte) []*Entry {
	var r record
	if err := json.Unmarshal(line, &r); err != nil {
		return nil
	}
	switch r.Type {
	case "ai-title":
		t.aiTitle = r.AITitle
		return nil
	case "last-prompt":
		t.lastPrompt = r.LastPrompt
		return nil
	case "user", "assistant":
	default:
		return nil
	}
	// The records of the subagents are ignored.
	if r.IsSidechain || r.IsMeta || r.Message == nil {
		return nil
	}

	if r.Type == "user" && r.Origin != nil && r.Origin.Kind == "human" {
		text := contentText(r.Message.Content)
		if t.firstPrompt == "" {
			t.firstPrompt = text
		}
		return []*Entry{{Kind: EntryKindUserPrompt, Time: r.Timestamp, Text: text}}
	}

	var blocks []contentBlock
	if err := json.Unmarshal(r.Message.Content, &blocks); err != nil {
		return nil
	}
	var entries []*Entry
	for _, b := range blocks {
		switch {
		case r.Type == "assistant" && b.Type == "text":
			entries = append(entries, &Entry{Kind: EntryKindAssistantText, Time: r.Timestamp, Text: b.Text})
		case r.Type == "assistant" && b.Type == "tool_use":
			entries = append(entries, &Entry{
				Kind:      EntryKindToolUse,
				Time:      r.Timestamp,
				Text:      truncate(toolInputSummary(b.Name, b.Input)),
				ToolName:  b.Name,
				ToolUseID: b.ID,
			})
		case r.Type == "user" && b.Type == "tool_result":
			entries = append(entries, &Entry{
				Kind:      EntryKindToolResult,
				Time:      r.Timestamp,
				Text:      truncate(contentText(b.Content)),
				ToolUseID: b.ToolUseID,
				IsError:   b.IsError,
			})
		}
	}
	return entries
}

// contentText returns the text of the content which is either a string or the blocks.
func contentText(content json.RawMessage) string {
	var s string
	if err := json.Unmarshal(content, &s); err == nil {
		return s
	}
	var blocks []contentBlock
	if err := json.Unmarshal(content, &blocks); err != nil {
		return ""
	}
	var texts []string
	for _, b := range blocks {
		if b.Type == "text" {
			texts = append(texts, b.Text)
		}
	}
	return strings.Join(texts, "\n")
}

// toolInputSummary returns the command or the file of the tool call. The other tools return the whole input.
func toolInputSummary(name string, input json.RawMessage) string {
	var in struct {
		Command  string `json:"command"`
		FilePath string `json:"file_path"`
		Pattern  string `json:"pattern"`
	}
	if err := json.Unmarshal(input, &in); err == nil {
		switch name {
		case "Bash":
			return in.Command
		case "Read", "Edit", "Write", "NotebookEdit":
			return in.FilePath
		case "Grep", "Glob":
			return in.Pattern
		}
	}
	return string(input)
}

func truncate(s string) string {
	if len(s) <= maxTextLength {
		return s
	}
	end := maxTextLength
	for end > 0 && !utf8.RuneStart(s[end]) {
		end--
	}
	return s[:end] + "…"
}
